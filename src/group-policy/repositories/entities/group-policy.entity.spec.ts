import { AccessPermissionStatusType } from '../../enums';
import { GroupPolicyEntity } from './group-policy.entity';

describe('GroupPolicyEntity', () => {
    describe('create', () => {
        it.each([
            [
                123,
                'Test Group Policy',
                true,
                AccessPermissionStatusType.Final,
                true,
                false,
                3600,
                true,
                false,
                true,
                true,
                false,
                true,
                false,
                true,
                false,
                true,
                false,
                true,
                false,
                1,
                2,
                3,
                4,
            ],
            [
                456,
                'Another Group Policy',
                false,
                AccessPermissionStatusType.NotDefined,
                false,
                true,
                7200,
                false,
                true,
                false,
                false,
                true,
                false,
                true,
                false,
                true,
                false,
                true,
                false,
                true,
                5,
                6,
                7,
                8,
            ],
        ])(
            'should create the entity with the provided parameters (id: %s, name: %s)',
            (
                id,
                name,
                hasEndpointsAccessPermission,
                accessPermissionStatusType,
                hasShareOtherTeamPermission,
                hasInviteExternalUserPermission,
                userSessionIdleTimeoutInSeconds,
                hasEnableExtendedAvailabilityModePermission,
                hasEditExternalKeyPermission,
                hasCollaboratePermission,
                hasCollaborateControlPermission,
                hasJumpClientPermission,
                hasLocalJumpPermission,
                hasRemoteJumpPermission,
                hasRemoteVncPermission,
                hasRemoteRdpPermission,
                hasShellJumpPermission,
                hasWebJumpPermission,
                hasProtocolTunnelPermission,
                hasSdStaticPortForExternalToolsPermission,
                defaultJumpItemRoleId,
                privateJumpItemRoleId,
                inferiorJumpItemRoleId,
                unassignedJumpItemRoleId,
            ) => {
                const groupPolicyEntity = GroupPolicyEntity.create(
                    id,
                    name,
                    hasEndpointsAccessPermission,
                    accessPermissionStatusType,
                    hasShareOtherTeamPermission,
                    hasInviteExternalUserPermission,
                    userSessionIdleTimeoutInSeconds,
                    hasEnableExtendedAvailabilityModePermission,
                    hasEditExternalKeyPermission,
                    hasCollaboratePermission,
                    hasCollaborateControlPermission,
                    hasJumpClientPermission,
                    hasLocalJumpPermission,
                    hasRemoteJumpPermission,
                    hasRemoteVncPermission,
                    hasRemoteRdpPermission,
                    hasShellJumpPermission,
                    hasWebJumpPermission,
                    hasProtocolTunnelPermission,
                    hasSdStaticPortForExternalToolsPermission,
                    defaultJumpItemRoleId,
                    privateJumpItemRoleId,
                    inferiorJumpItemRoleId,
                    unassignedJumpItemRoleId,
                );

                expect(groupPolicyEntity).toBeInstanceOf(GroupPolicyEntity);
                expect(groupPolicyEntity.id).toBe(id);
                expect(groupPolicyEntity.name).toBe(name);
                expect(groupPolicyEntity.hasEndpointsAccessPermission).toBe(hasEndpointsAccessPermission);
                expect(groupPolicyEntity.accessPermissionStatusType).toBe(accessPermissionStatusType);
                expect(groupPolicyEntity.hasShareOtherTeamPermission).toBe(hasShareOtherTeamPermission);
                expect(groupPolicyEntity.hasInviteExternalUserPermission).toBe(hasInviteExternalUserPermission);
                expect(groupPolicyEntity.userSessionIdleTimeoutInSeconds).toBe(userSessionIdleTimeoutInSeconds);
                expect(groupPolicyEntity.hasEnableExtendedAvailabilityModePermission).toBe(
                    hasEnableExtendedAvailabilityModePermission,
                );
                expect(groupPolicyEntity.hasEditExternalKeyPermission).toBe(hasEditExternalKeyPermission);
                expect(groupPolicyEntity.hasCollaboratePermission).toBe(hasCollaboratePermission);
                expect(groupPolicyEntity.hasCollaborateControlPermission).toBe(hasCollaborateControlPermission);
                expect(groupPolicyEntity.hasJumpClientPermission).toBe(hasJumpClientPermission);
                expect(groupPolicyEntity.hasLocalJumpPermission).toBe(hasLocalJumpPermission);
                expect(groupPolicyEntity.hasRemoteJumpPermission).toBe(hasRemoteJumpPermission);
                expect(groupPolicyEntity.hasRemoteVncPermission).toBe(hasRemoteVncPermission);
                expect(groupPolicyEntity.hasRemoteRdpPermission).toBe(hasRemoteRdpPermission);
                expect(groupPolicyEntity.hasShellJumpPermission).toBe(hasShellJumpPermission);
                expect(groupPolicyEntity.hasWebJumpPermission).toBe(hasWebJumpPermission);
                expect(groupPolicyEntity.hasProtocolTunnelPermission).toBe(hasProtocolTunnelPermission);
                expect(groupPolicyEntity.hasSdStaticPortForExternalToolsPermission).toBe(
                    hasSdStaticPortForExternalToolsPermission,
                );
                expect(groupPolicyEntity.defaultJumpItemRoleId).toBe(defaultJumpItemRoleId);
                expect(groupPolicyEntity.privateJumpItemRoleId).toBe(privateJumpItemRoleId);
                expect(groupPolicyEntity.inferiorJumpItemRoleId).toBe(inferiorJumpItemRoleId);
                expect(groupPolicyEntity.unassignedJumpItemRoleId).toBe(unassignedJumpItemRoleId);
            },
        );
    });
});
